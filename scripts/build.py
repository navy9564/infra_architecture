#!/usr/bin/env python3
"""
content/*.yaml + 참조된 IaC 파일 -> assets/js/data/bundle.js

  python3 scripts/build.py          # 번들 생성
  python3 scripts/build.py --check  # 번들이 최신인지 검사 (CI)

번들을 JS 파일로 만드는 이유: file:// 로 index.html 을 직접 열어도(fetch 불가)
GitHub Pages 와 동일하게 동작시키기 위함.
"""
import glob
import json
import os
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "assets", "js", "data", "bundle.js")
METHODS = ("terraform", "ansible", "helm")


def load_yaml(path):
    with open(path, encoding="utf-8") as f:
        return yaml.safe_load(f)


def main():
    meta = load_yaml(os.path.join(ROOT, "content", "meta.yaml"))
    components = []
    for path in sorted(glob.glob(os.path.join(ROOT, "content", "components", "*.yaml"))):
        components.extend(load_yaml(path) or [])

    ids = set()
    snippets = {}
    errors = []
    for c in components:
        if c["id"] in ids:
            errors.append(f"duplicate id: {c['id']}")
        ids.add(c["id"])
        for m in METHODS:
            g = (c.get("guides") or {}).get(m)
            if not g:
                errors.append(f"{c['id']}: missing guide '{m}'")
                continue
            for s in g.get("steps", []):
                f = s.get("file")
                if not f:
                    continue
                p = os.path.join(ROOT, f)
                if not os.path.isfile(p):
                    errors.append(f"{c['id']}/{m}: file not found -> {f}")
                    continue
                with open(p, encoding="utf-8") as fh:
                    snippets[f] = fh.read()

    if errors:
        print("\n".join("ERROR " + e for e in errors))
        sys.exit(1)

    data = {"meta": meta, "components": components, "snippets": snippets}
    body = (
        "/* AUTO-GENERATED by scripts/build.py - DO NOT EDIT. Edit content/*.yaml instead. */\n"
        "window.ARCH = " + json.dumps(data, ensure_ascii=False, indent=1, default=str) + ";\n"
    )

    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != body:
            print("bundle.js is outdated. Run: python3 scripts/build.py")
            sys.exit(1)
        print("bundle.js is up to date")
        return

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(body)
    print(f"wrote {os.path.relpath(OUT, ROOT)}: {len(components)} components, {len(snippets)} snippets, {len(body)//1024} KB")


if __name__ == "__main__":
    main()
